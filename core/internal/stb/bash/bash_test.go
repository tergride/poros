func TestHash(t *testing.T) {
	for _, c := range []struct {
		level, n int
		want     string
	}{
		{128, 0, "114C3DFAE373D9BCBC3602D6386F2D6A2059BA1BF9048DBAA5146A6CB775709D"},
		{128, 127, "3D7F4EFA00E9BA33FEED259986567DCF5C6D12D51057A968F14F06CC0F905961"},
		{128, 128, "D7F428311254B8B2D00F7F9EEFBD8F3025FA87C4BABD1BDDBE87E35B7AC80DD6"},
		{128, 135, "1393FA1B65172F2D18946AEAE576FA1CF54FDD354A0CB2974A997DC4865D3100"},
		{192, 95, "64334AF830D33F63E9ACDFA184E32522103FFF5C6860110A2CD369EDBC04387C501D8F92F749AE4DE15A8305C353D64D"},
		{192, 96, "D06EFBC16FD6C0880CBFC6A4E3D65AB101FA82826934190FAABEBFBFFEDE93B22B85EA72A7FB3147A133A5A8FEBD8320"},
		{192, 108, "FF763296571E2377E71A1538070CC0DE88888606F32EEE6B082788D246686B00FC05A17405C5517699DA44B7EF5F55AB"},
		{256, 63, "2A66C87C189C12E255239406123BDEDBF19955EAF0808B2AD705E249220845E20F4786FB6765D0B5C48984B1B16556EF19EA8192B985E4233D9C09508D6339E7"},
		{256, 64, "07ABBF8580E7E5A321E9B940F667AE209E2952CEF557978AE743DB086BAB4885B708233C3F5541DF8AAFC3611482FDE498E58B3379A6622DAC2664C9C118A162"},
		{256, 127, "526073918F97928E9D15508385F42F03ADE3211A23900A30131F8A1E3E1EE21CC09D13CFF6981101235D895746A4643F0AA62B0A7BC98A269E4507A257F0D4EE"},
		{256, 192, "8724C7FF8A2A83F22E38CB9763777B96A70ABA3444F214C763D93CD6D19FCFDE6C3D3931857C4FF6CCCD49BD99852FE9EAA7495ECCDD96B571E0EDCF47F89768"},
	} {
		d := New(c.level)
		d.Write(h(c.n))
		expect(t, "A.3", d.Sum(nil), c.want)
		// The same value whatever the pieces of the data, and Sum does not change the state.
		for split := 0; split <= c.n; split += 7 {
			d.Reset()
			d.Write(h(split))
			d.Sum(nil)
			d.Write(h(c.n)[split:])
			expect(t, "split", d.Sum(nil), c.want)
		}
	}
	if New512().BlockSize() != 64 || New384().BlockSize() != 96 || New256().BlockSize() != 128 {
		t.Fatal("the blocks of HMAC differ from bee2evp")
	}
}
