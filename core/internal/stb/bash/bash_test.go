// The vectors come from annex A of STB 34.101.77, as bee2 checks them: the data are slices of the belt table H.

func expect(t *testing.T, name string, got []byte, want string) {
	t.Helper()
	w, err := hex.DecodeString(want)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, w) {
		t.Errorf("%s:\n got %X\nwant %X", name, got, w)
	}
}

func h(n int) []byte {
	table := belt.H
	return append([]byte(nil), table[:n]...)
}

